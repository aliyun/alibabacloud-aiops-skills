#!/usr/bin/env python3
"""离线文档用例自检：结构、身份、文件引用、执行依赖与静态覆盖统计。

python3 scripts/validate_evals.py [--quiet]
只读本地文件；不运行模型、aliyun、SDK 或云端请求。
"""
import argparse
import json
from pathlib import Path
import re
import sys
from collections import Counter
from uuid import UUID

ROOT = Path(__file__).resolve().parents[1]
EVALS_DIR = ROOT / 'evals/scenarios/autoGenerated'
ERROR_CODES = {
    'permission': 'Forbidden.AccessDenied',
    'parameter': 'InvalidParameter',
    'internal': 'InternalError',
    'throttling': 'Throttling',
}
errors = []
warnings = []


def err(message):
    errors.append(message)


def load_cases():
    cases = []
    for path in sorted(EVALS_DIR.glob('*.jsonc')):
        try:
            data = json.loads(path.read_text(encoding='utf-8'))
        except (OSError, ValueError) as exc:
            err(f'{path.name}: JSON 解析失败：{exc}')
            continue
        if not isinstance(data, dict) or data.get('$version') != '2':
            err(f'{path.name}: $version 必须为 "2"')
            continue
        case = data.get('evals')
        if not isinstance(case, dict):
            err(f'{path.name}: 缺少 evals 对象')
            continue
        for field in ('uuid', 'name', 'prompt', 'expected_output'):
            if not isinstance(case.get(field), str) or not case[field].strip():
                err(f'{path.name}: evals.{field} 必须为非空字符串')
        try:
            UUID(case.get('uuid', ''))
        except (ValueError, TypeError, AttributeError):
            err(f'{path.name}: uuid 非法')
        cases.append((path.name, case))
    if not cases:
        err('没有可校验的用例')
    return cases


def check_uniqueness(cases):
    for field in ('uuid', 'name'):
        seen = set()
        for filename, case in cases:
            value = case.get(field)
            if isinstance(value, str):
                if value in seen:
                    err(f'{filename}: {field} 重复：{value}')
                seen.add(value)


def check_name_matches_file(filename, case):
    stem = Path(filename).stem
    expected = 'route-to-' + re.sub(r'^route-\d+-', '', stem) if stem.startswith('route-') else stem
    if case.get('name') != expected:
        err(f'{filename}: name 应为 {expected}（保留历史身份）')


def check_skill_paths(filename, case):
    # 检查所有正文与断言中的 references 文件路径，不只检查 SKILL.md。
    blob = json.dumps(case, ensure_ascii=False).replace('\\\\.', '.')
    paths = set(re.findall(r'references/[A-Za-z0-9_./-]+\.(?:md|json)', blob))
    for relative in paths:
        path = (ROOT / relative).resolve()
        if not path.is_relative_to(ROOT.resolve()) or not path.is_file():
            err(f'{filename}: 引用了不存在或越界的文件 {relative}')


def check_assertions(filename, case):
    expectations = case.get('expectations')
    if not isinstance(expectations, list):
        err(f'{filename}: expectations 必须为数组')
        return
    if filename.startswith('neg-'):
        if expectations:
            err(f'{filename}: 负向用例不应有正向文件命中断言')
    elif not any(isinstance(e, dict) and e.get('id') == 'read-target-skill' for e in expectations):
        err(f'{filename}: 缺少 read-target-skill 断言')
    ids = set()
    for assertion in expectations:
        if not isinstance(assertion, dict):
            err(f'{filename}: 断言必须为对象')
            continue
        identity = assertion.get('id')
        if not isinstance(identity, str) or not identity or identity in ids:
            err(f'{filename}: 断言 id 缺失或重复')
        else:
            ids.add(identity)
        value = assertion.get('value')
        if assertion.get('type') != 'contains' or not isinstance(value, str) or not value.startswith('references/'):
            err(f'{filename}: 离线正向断言应使用 contains 命中具体 references 文件')
        elif not (ROOT / value).is_file():
            err(f'{filename}: 断言目标不存在：{value}')
    # 文件命中已构成完整断言，不要求重复添加最终回答措辞检查。
    result = case.get('result_verification', {})
    if not isinstance(result, dict):
        err(f'{filename}: result_verification 必须为对象或省略')
    else:
        for check in result.get('checks', []):
            if check.get('name') in {'mention-target-skill', 'mention-key-capability', 'hitl-confirmation'}:
                err(f'{filename}: 不应重复要求最终回答中的技能名、命令名或确认话术')
    forbidden = case.get('forbidden', [])
    if not isinstance(forbidden, list) or not forbidden:
        err(f'{filename}: forbidden 为空（保留凭证保密禁则）')
        return
    credentials = [rule for rule in forbidden if isinstance(rule, dict) and 'LTAI' in json.dumps(rule)]
    if not credentials:
        err(f'{filename}: 缺少凭证保密禁则')
    for rule in credentials:
        if rule.get('target') != 'final_answer':
            err(f'{filename}: 凭证保密禁则必须限定 final_answer，不能把读文档判成泄露')


def error_category(filename):
    if filename.startswith('err-'):
        return filename.split('-')[1]
    if filename.startswith('mock-probe-'):
        return 'throttling'  # 保留历史文件名，现为固定限流响应的文档分析用例。
    return None


def check_offline_contract(filename, case):
    if '本次是离线文档评测' not in case.get('prompt', ''):
        err(f'{filename}: prompt 缺少离线范围声明')
    if case.get('mocks') or any(e.get('type') == 'mock_action' for e in case.get('expectations', []) if isinstance(e, dict)):
        err(f'{filename}: 离线文档用例不应依赖运行时 mock 或 mock_action')
    category = error_category(filename)
    if category and ERROR_CODES.get(category, '') not in case.get('prompt', ''):
        err(f'{filename}: 缺少 {category} 的固定错误响应样例')


def report_coverage(cases):
    skills = {str(path.relative_to(ROOT)) for path in (ROOT / 'references').rglob('SKILL.md')}
    referenced = {e['value'] for _, case in cases for e in case.get('expectations', [])
                  if isinstance(e, dict) and e.get('type') == 'contains' and isinstance(e.get('value'), str)}
    covered = skills & referenced
    positives = [case for name, case in cases if not name.startswith('neg-')]
    asserted = sum(bool(case.get('expectations')) for case in positives)
    categories = Counter(error_category(name) for name, _ in cases)
    print('== 本地静态统计（不代表平台模型评测通过率） ==')
    print(f'用例总数：{len(cases)}')
    print(f'子技能文件引用覆盖：{len(covered)}/{len(skills)}')
    print(f'正向用例含文件命中断言：{asserted}/{len(positives)}')
    print('错误样例场景：' + '，'.join(f'{kind}({categories[kind]})' for kind in ERROR_CODES))
    print('IC 场景：' + '，'.join(f'{kind}({sum(name.startswith("ic-" + kind + "-") for name, _ in cases)})'
                              for kind in ('complete', 'autofill', 'unclear')))
    print(f'Trigger 场景：原文 {sum(name.startswith("trigger-desc-") for name, _ in cases)}，'
          f'同义表达 {sum(name.startswith("trigger-syn-") for name, _ in cases)}')
    print(f'版本指导场景：{sum(name.startswith("gate-") for name, _ in cases)}')
    if skills - covered:
        print('未引用子技能：' + ', '.join(sorted(skills - covered)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--quiet', action='store_true')
    args = parser.parse_args()
    errors.clear()
    warnings.clear()
    cases = load_cases()
    check_uniqueness(cases)
    for filename, case in cases:
        check_name_matches_file(filename, case)
        check_skill_paths(filename, case)
        check_assertions(filename, case)
        check_offline_contract(filename, case)
    if not args.quiet:
        report_coverage(cases)
    for message in errors:
        print('ERROR ' + message)
    print(f'\n{len(errors)} error(s), {len(warnings)} warning(s)')
    return int(bool(errors))


if __name__ == '__main__':
    sys.exit(main())
