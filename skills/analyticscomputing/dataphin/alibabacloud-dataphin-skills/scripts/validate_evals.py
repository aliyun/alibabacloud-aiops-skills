#!/usr/bin/env python3
"""评测用例自检脚本。

用法：
    python3 scripts/validate_evals.py            # 校验 + 输出覆盖度统计
    python3 scripts/validate_evals.py --quiet    # 只在有问题时输出

校验项：
1. JSONC 可解析、顶层结构合法（$version / evals.uuid / name / prompt / expected_output）
2. uuid 全局唯一、name 全局唯一
3. 新式用例（trigger-* / ic-* / neg-*）的 name 必须与文件名主干一致
4. expectations / forbidden 里引用的 references/**/SKILL.md 路径必须真实存在
5. 正向用例必须至少有 1 条 read-target-skill 断言；负向用例必须没有 expectations
6. 输出覆盖度统计：能力覆盖率 / 断言覆盖率 / IC 象限 / Trigger 变体 / 环境版本闸门，对齐评测报告的四项指标

退出码：0 = 无 ERROR；1 = 存在 ERROR。
"""
import argparse
import json
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVALS_DIR = os.path.join(ROOT, "evals/scenarios/autoGenerated")
REFS_DIR = os.path.join(ROOT, "references")
MODULES = [
    "assets", "dataplan", "datasecurity", "dataservice", "dev",
    "knowledge-graph", "manage", "ops", "pipeline", "unstructured-data",
]
ERROR_TYPES = ["permission", "parameter", "throttling", "internal"]
# aliyun CLI mock 记录的必填字段（实测：缺 name 或 stderr 会让加载器整体失败，
# 报 "load mock data failed mock record name/stderr is required"，进而 mock 全部失效）。
MOCK_REQUIRED_FIELDS = ["id", "name", "cmd", "exit_code", "times", "stdout", "stderr"]

errors = []
warnings = []


def err(msg):
    errors.append(msg)


def warn(msg):
    warnings.append(msg)


def all_skill_dirs():
    """返回 {module: [skill 相对路径, ...]}，skill 相对路径可能含二级目录。"""
    result = defaultdict(list)
    for module in MODULES:
        base = os.path.join(REFS_DIR, module)
        if not os.path.isdir(base):
            continue
        for dirpath, _dirnames, filenames in os.walk(base):
            if "SKILL.md" in filenames:
                rel = os.path.relpath(dirpath, base)
                result[module].append(rel)
    return result


def load_cases():
    cases = []
    for name in sorted(os.listdir(EVALS_DIR)):
        if not name.endswith(".jsonc"):
            continue
        path = os.path.join(EVALS_DIR, name)
        try:
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
        except Exception as exc:  # noqa: BLE001
            err(f"{name}: JSON 解析失败：{exc}")
            continue
        if data.get("$version") != "2":
            err(f"{name}: 缺少或非法 $version（应为 \"2\"）")
        evals = data.get("evals")
        if not isinstance(evals, dict):
            err(f"{name}: 缺少 evals 对象")
            continue
        for field in ("uuid", "name", "prompt", "expected_output"):
            if not evals.get(field):
                err(f"{name}: evals.{field} 缺失或为空")
        cases.append((name, evals))
    return cases


def check_uniqueness(cases):
    seen_uuid, seen_name = {}, {}
    for name, evals in cases:
        u, n = evals.get("uuid"), evals.get("name")
        if u in seen_uuid:
            err(f"{name}: uuid 与 {seen_uuid[u]} 重复（{u}）")
        seen_uuid[u] = name
        if n in seen_name:
            err(f"{name}: name 与 {seen_name[n]} 重复（{n}）")
        seen_name[n] = name


def check_name_matches_file(file_name, evals):
    stem = file_name[: -len(".jsonc")]
    if stem.startswith("route-"):
        # 旧式命名：route-NN-<module>-<skill>.jsonc / name=route-to-<module>-<skill>
        expected = "route-to-" + re.sub(r"^route-\d+-", "", stem)
        if evals["name"] != expected:
            warn(f"{file_name}: name={evals['name']}，按文件名推导应为 {expected}")
    else:
        if evals["name"] != stem:
            err(f"{file_name}: name={evals['name']} 与文件名主干 {stem} 不一致")


def check_skill_paths(file_name, evals):
    blob = json.dumps(evals, ensure_ascii=False)
    for raw in set(re.findall(r"references/[a-z0-9\-/]+/SKILL\\\\?\.md", blob)):
        rel = raw.replace("\\\\", "").replace("\\.", ".")
        if not os.path.isfile(os.path.join(ROOT, rel)):
            err(f"{file_name}: 断言引用了不存在的文件 {rel}")


def check_assertions(file_name, evals):
    is_negative = file_name.startswith("neg-")
    expectations = evals.get("expectations", [])
    checks = (evals.get("result_verification") or {}).get("checks", [])
    if is_negative:
        if expectations:
            err(f"{file_name}: 负向用例不应有 expectations（应只用 forbidden + response 断言）")
    else:
        if not any(e.get("id") == "read-target-skill" for e in expectations) and not file_name.startswith("ic-unclear-"):
            err(f"{file_name}: 缺少 read-target-skill 断言")
    if not checks:
        err(f"{file_name}: result_verification.checks 为空")
    if not evals.get("forbidden"):
        err(f"{file_name}: forbidden 为空（至少需要凭证保密禁则）")
    cred_rules = [f for f in evals.get("forbidden", []) if "LTAI" in json.dumps(f, ensure_ascii=False)]
    if not cred_rules:
        warn(f"{file_name}: 未见凭证保密禁则（LTAI）")
    for rule in cred_rules:
        # 不写 target 时判定范围退化成整条执行日志，而根 SKILL.md §4.1 正文本身含 LTAI
        # 字面量（AK 前缀启发式），会把读文档的正常行为判成凭证泄露假红。详见 evals/README.md §2.4。
        if rule.get("target") != "final_answer":
            err(f'{file_name}: 凭证保密禁则必须显式声明 "target": "final_answer"（否则整条执行日志都会被检，产生假红）')


def check_mocks(file_name, evals):
    """校验 evals.mocks 与 mock_action 的格式与互相引用。

    这些约束全部由平台实跑取证得出，不是猜测：
    - 缺 name 或 stderr → CLI 报 "load mock data failed mock record ... is required"，整份 mock 失效；
    - cmd 带 aliyun 前缀 → 匹配不上；
    - 贴写的 `xxx*` 只是单 token 前缀通配，不吞后续参数；只有独立的 ` *` token 才吞掉全部参数。
      匹配不上的后果不是报错而是**穿透到真实云端**，因此这里报 ERROR 而不是 WARN。
    """
    mocks = evals.get("mocks") or []
    mock_actions = [e for e in evals.get("expectations", []) if e.get("type") == "mock_action"]
    if file_name.startswith("err-") and not mocks:
        err(f"{file_name}: err-* 用例必须用 evals.mocks 注入错误（缺 mocks）")
    if file_name.startswith("err-") and not mock_actions:
        err(f"{file_name}: err-* 用例必须有 mock_action 断言")
    mock_ids = set()
    for mock in mocks:
        name = mock.get("name") or mock.get("id") or "<匿名>"
        mock_ids.add(mock.get("id"))
        missing = [f for f in MOCK_REQUIRED_FIELDS if f not in mock]
        if missing:
            err(f"{file_name}: mock「{name}」缺字段 {missing}（缺 name/stderr 会让 CLI 加载器整份 mock 失效）")
        cmd = mock.get("cmd", "")
        if cmd.startswith("aliyun"):
            err(f"{file_name}: mock「{name}」的 cmd 不得带 aliyun 前缀（当前：{cmd}）")
        if "*" in cmd and not cmd.endswith(" *"):
            err(f"{file_name}: mock「{name}」的 cmd 通配符必须写成独立的 ` *` 结尾，贴写的 `xxx*` 只是单 token 前缀通配、"
                f"带参调用会匹配失败并穿透到真实云端（当前：{cmd}）")
    for action in mock_actions:
        if action.get("mock_id") not in mock_ids:
            err(f"{file_name}: mock_action「{action.get('id')}」的 mock_id={action.get('mock_id')} 在 mocks 里不存在")
        etype = action.get("error_type")
        if etype is not None and etype not in ERROR_TYPES:
            err(f"{file_name}: mock_action「{action.get('id')}」的 error_type={etype} 不在 {ERROR_TYPES} 之内")


def report_coverage(cases, skill_dirs):
    total_skills = sum(len(v) for v in skill_dirs.values())
    covered = set()
    for name, evals in cases:
        if name.startswith("neg-"):
            continue
        blob = json.dumps(evals, ensure_ascii=False)
        for module, skills in skill_dirs.items():
            for skill in skills:
                if f"references/{module}/{skill}/SKILL" in blob.replace("\\\\", ""):
                    covered.add(f"{module}/{skill}")
    positives = [c for c in cases if not c[0].startswith("neg-")]
    with_business_assert = [
        c for c in positives
        if any(chk.get("name") not in (None, "mention-target-skill")
               for chk in (c[1].get("result_verification") or {}).get("checks", []))
    ]
    ic = {
        "信息完整": [c[0] for c in cases if c[0].startswith("ic-complete-")],
        "可自动补全": [c[0] for c in cases if c[0].startswith("ic-autofill-")],
        "候选不唯一需确认": [c[0] for c in cases if c[0].startswith("route-")],
        "意图不清需澄清": [c[0] for c in cases if c[0].startswith("ic-unclear-")],
    }
    print("== 覆盖度统计 ==")
    print(f"用例总数：{len(cases)}（正向 {len(positives)} / 负向 {len(cases) - len(positives)}）")
    print(f"能力覆盖率：{len(covered)}/{total_skills} = {len(covered) * 100 // max(total_skills, 1)}%")
    print(f"断言覆盖率（含业务级断言的正向用例）：{len(with_business_assert)}/{len(positives)}"
          f" = {len(with_business_assert) * 100 // max(len(positives), 1)}%")
    filled = sum(1 for v in ic.values() if v)
    print(f"IC 象限：{filled}/4 " + "，".join(f"{k}({len(v)})" for k, v in ic.items()))
    err_hits = {
        t: [c[0] for c in cases
            if any(e.get("error_type") == t for e in c[1].get("expectations", []))]
        for t in ERROR_TYPES
    }
    covered_types = [t for t, v in err_hits.items() if v]
    print(f"错误类型覆盖：{len(covered_types)}/4 " + "，".join(f"{t}({len(v)})" for t, v in err_hits.items()))
    print(f"Trigger 变体：description 原文 {sum(1 for c in cases if c[0].startswith('trigger-desc-'))} 条，"
          f"同义/句式变体 {sum(1 for c in cases if c[0].startswith('trigger-syn-'))} 条")
    # 闸门实现在父层，与子 skill 数量无关，故不计入能力覆盖率，单独成一行使其可见。
    print(f"环境/版本闸门用例：{sum(1 for c in cases if c[0].startswith('gate-'))} 条")
    uncovered = sorted(
        f"{m}/{s}" for m, ss in skill_dirs.items() for s in ss if f"{m}/{s}" not in covered
    )
    if uncovered:
        print(f"未覆盖 skill：{uncovered}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    skill_dirs = all_skill_dirs()
    cases = load_cases()
    check_uniqueness(cases)
    for file_name, evals in cases:
        check_name_matches_file(file_name, evals)
        check_skill_paths(file_name, evals)
        check_assertions(file_name, evals)
        check_mocks(file_name, evals)

    if not args.quiet:
        report_coverage(cases, skill_dirs)
        print()
    for w in warnings:
        print(f"WARN  {w}")
    for e in errors:
        print(f"ERROR {e}")
    print(f"\n{len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
