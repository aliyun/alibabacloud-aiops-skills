    def analyze_scenario_specific(self) -> Dict[str, Any]:
        """Perform scenario-specific checks based on cutover scenario type (added in v3.0)

        Returns:
            Scenario-specific analysis result
        """
        result = {
            'scenario_type': self.scenario_type,
            'scenario_name': self.scenario_config['name'],
            'checks_performed': [],
            'issues_found': [],
            'score': 100
        }

        # Get focus items for the current scenario
        if self.scenario_type == 'batch':
            focus_items = DATABASE_BATCH_FOCUS
        elif self.scenario_type == 'full':
            # Full cutover needs to check both batch-specific points + full cutover exclusive points
            focus_items = DATABASE_FULL_FOCUS + DATABASE_BATCH_FOCUS
        else:
            focus_items = OTHER_FOCUS

        # Extract text content from all Sheets for checking
        all_text = self._extract_all_sheet_text()

        # Check each item
        score_deduction = 0
        for item in focus_items:
            check_result = self._check_scenario_item(item, all_text)
            result['checks_performed'].append({
                'id': item['id'],
                'name': item['name'],
                'passed': check_result['passed'],
                'message': check_result['message']
            })

            if not check_result['passed']:
                result['issues_found'].append(check_result['message'])
                self.issues.append({
                    'severity': item['severity'],
                    'category': item['category'],
                    'message': check_result['message']
                })
                # Deduct score based on severity
                if item['severity'] == 'CRITICAL':
                    score_deduction += 10
                elif item['severity'] == 'HIGH':
                    score_deduction += 5

        result['score'] = max(0, 100 - score_deduction)
        result['total_checks'] = len(focus_items)
        result['passed_checks'] = sum(1 for c in result['checks_performed'] if c['passed'])
        result['failed_checks'] = result['total_checks'] - result['passed_checks']

        self.analysis_result['scenario_specific'] = result
        return result

