    def calculate_overall_score(self) -> Dict[str, Any]:
        """Calculate overall score

        Returns:
            Scoring result
        """
        checklist = self.analysis_result.get('checklist', {})
        process = self.analysis_result.get('process', {})
        rollback = self.analysis_result.get('rollback', {})
        domains = self.analysis_result.get('domains', {})
        data_migration = self.analysis_result.get('data_migration', {})

        # Use the score field already calculated for each dimension (if it exists), otherwise fall back to default
        checklist_score = checklist.get('score', 50)
        process_score = process.get('score', 50)
        rollback_score = rollback.get('score', 50)
        resource_score = self._calculate_resource_score()
        monitoring_score = self._calculate_monitoring_score()

        # Organization effectiveness score (based on CheckList responsibility assignment)
        org_score = 100
        if checklist.get('empty_owner_count', 0) > 0:
            org_score -= 30
        if checklist.get('empty_time_count', 0) > 5:
            org_score -= 10
        org_score = max(0, org_score)

        # v4.3: Dynamic weights — only score "dimensions actually participating in review" and normalize.
        # Avoids unreviewed CheckList/domains/data migration using placeholder score of 50 to drag down total.
        checklist_reviewed = 'checklist' in self.sheets_to_check
        weights = {}
        if checklist_reviewed:
            weights['checklist'] = 0.20
        if 'process' in self.sheets_to_check:
            weights['process'] = 0.25
        if 'rollback' in self.sheets_to_check:
            weights['rollback'] = 0.25
        # Resource config, org effectiveness, and monitoring/verification all depend on CheckList content
        # (owners/time/monitoring items). Not scored in narrow-range mode (only cutover steps + rollback steps)
        # to avoid penalizing with missing items.
        if checklist_reviewed:
            weights['monitoring'] = 0.10
            weights['resource'] = 0.15
            weights['organization'] = 0.05

        scores = {
            'checklist': checklist_score,
            'process': process_score,
            'rollback': rollback_score,
            'resource': resource_score,
            'monitoring': monitoring_score,
            'organization': org_score,
        }

        weight_sum = sum(weights.values()) or 1
        overall_score = sum(scores[k] * w for k, w in weights.items()) / weight_sum

        # Determine risk level
        if overall_score >= 90:
            risk_level = 'LOW'
            recommendation = 'Can proceed with cutover'
        elif overall_score >= 70:
            risk_level = 'MEDIUM'
            recommendation = 'Recommend supplementing and improving before execution'
        elif overall_score >= 50:
            risk_level = 'HIGH'
            recommendation = 'Must rectify and re-review before execution'
        else:
            risk_level = 'CRITICAL'
            recommendation = 'Not recommended to proceed with cutover using this plan'

        result = {
            'overall_score': round(overall_score, 1),
            'risk_level': risk_level,
            'recommendation': recommendation,
            'dimension_scores': {
                'checklist': checklist_score,
                'process': process_score,
                'rollback': rollback_score,
                'resource': resource_score,
                'monitoring': monitoring_score,
                'organization': org_score
            },
            # v4.3: Record dimensions actually participating in scoring and pre-normalization weights for report traceability
            'effective_weights': {k: round(v / weight_sum, 4) for k, v in weights.items()},
            'reviewed_sheets': list(self.sheets_to_check)
        }

        self.analysis_result['overall'] = result
        return result
    
