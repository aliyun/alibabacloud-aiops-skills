    def _issue_key_phrase(self, message: str) -> str:
        """Extract a short identifier phrase for topic matching and hit-item display.

        The raw message often carries the full check_logic text; using it directly
        for keyword matching causes cross-contamination (e.g., "restore traffic" body
        mentions maintenance notice, gets misclassified into that topic).
        Therefore, prefer [xxx] bracket content first, then the first sentence.
        """
        if not message:
            return ''
        text = re.sub(r'^[^\w\u4e00-\u9fff\[]+', '', message).strip()
        m = re.search(r'\[([^\]]{2,60})\]', text)
        if m:
            return m.group(1).strip()
        head = re.split(r'[。\n]', text, 1)[0].strip()
        return (head or text)[:60]

    def _match_topic(self, category: str, key_phrase: str) -> Optional[Dict[str, Any]]:
        """Assign an issue to a topic (ISSUE_TOPICS order-sensitive, first match wins)."""
        haystack = f"{category} {key_phrase}".lower()
        for topic in ISSUE_TOPICS:
            for kw in topic.get('match_any', []):
                if kw.lower() in haystack:
                    return topic
        return None

    def _consolidate_issues(self) -> Tuple[List[Dict[str, Any]], List[Dict[str, str]]]:
        """v4.4 issue consolidation layer: topic merging + conditional suppression + noise discard.

        Returns:
            (consolidated issue group list, suppression note list)
        """
        sev_order = {'CRITICAL': 0, 'HIGH': 1, 'MEDIUM': 2, 'LOW': 3}

        # --- 1. Conditional suppression (based on full text of reviewed Sheets) ---
        all_text = self._extract_all_sheet_text().lower()
        active_rules: List[Dict[str, Any]] = []
        for rule in SUPPRESSION_RULES:
            if any(kw.lower() in all_text for kw in rule.get('when_any', [])):
                active_rules.append(rule)

        def _suppressed(topic_id: str, message: str) -> Optional[Dict[str, Any]]:
            for rule in active_rules:
                if topic_id not in rule.get('topics', []):
                    continue
                only = rule.get('only_messages_any') or []
                if not only or any(kw.lower() in message.lower() for kw in only):
                    return rule
            return None

        # --- 2. Group by topic ---
        groups: Dict[str, Dict[str, Any]] = {}
        misc: List[Dict[str, Any]] = []
        suppressed_notes: Dict[str, Dict[str, Any]] = {}

        for issue in self.issues:
            raw_category = str(issue.get('category', 'Uncategorized'))
            message = str(issue.get('message', '')).strip()
            severity = issue.get('severity', 'LOW')
            key_phrase = self._issue_key_phrase(message)
            topic = self._match_topic(raw_category, key_phrase)

            if topic is None:
                misc.append({
                    'topic_id': None,
                    'core': False,
                    'severity': severity,
                    'category': self._rewrite_category(raw_category),
                    'message': message,
                    'hits': [message],
                })
                continue

            if topic.get('drop'):
                continue

            rule = _suppressed(topic['id'], message)
            if rule:
                note = suppressed_notes.setdefault(rule['id'], {
                    'reason': rule.get('reason', ''),
                    'count': 0,
                })
                note['count'] += 1
                continue

            g = groups.get(topic['id'])
            if g is None:
                g = {
                    'topic_id': topic['id'],
                    'core': bool(topic.get('core')),
                    'severity': severity,
                    'category': self._rewrite_category(topic.get('category', 'Uncategorized')),
                    'title': topic.get('title', ''),
                    'risk': topic.get('risk', ''),
                    'advice': topic.get('advice', ''),
                    'hits': [],
                    'order': ISSUE_TOPICS.index(topic),
                }
                groups[topic['id']] = g

            # Take the highest severity within the group
            if sev_order.get(severity, 9) < sev_order.get(g['severity'], 9):
                g['severity'] = severity

            # Record original hit check items (using short key phrases, deduplicated)
            hit_title = key_phrase or self._parse_issue_message(message)[0]
            if hit_title and hit_title not in g['hits']:
                g['hits'].append(hit_title)

        # --- 3. Sort: severity first, then topic definition order ---
        result = sorted(
            groups.values(),
            key=lambda g: (sev_order.get(g['severity'], 9), g['order'])
        )

        # Deduplicate misc items and append at end (not part of core risks)
        seen_misc = set()
        for m in sorted(misc, key=lambda x: sev_order.get(x['severity'], 9)):
            key = (m['category'], m['message'][:120])
            if key in seen_misc:
                continue
            seen_misc.add(key)
            title, detail, suggestion = self._parse_issue_message(m['message'])
            m.update({'title': title, 'risk': detail, 'advice': suggestion, 'hits': []})
            result.append(m)

        notes = [
            {'reason': v['reason'], 'count': v['count']}
            for v in suppressed_notes.values()
        ]
        return result, notes

    def _split_issues_by_priority(self) -> Tuple[List[Dict], List[Dict]]:
        """v4.4: Split issues into must-confirm / needs-attention based on topic consolidation.

        Must-confirm = core risk topics with severity CRITICAL/HIGH, capped at MAX_MUST_CONFIRM_ITEMS;
        the rest (non-core topics, uncategorized issues, overflow core items) go to needs-attention.
        """
        sev_label_map = {
            'CRITICAL': '🔴 Critical',
            'HIGH': '🟠 High',
            'MEDIUM': '🟡 Medium',
            'LOW': '🔵 Low',
        }

        groups, suppressed_notes = self._consolidate_issues()
        self.suppressed_notes = suppressed_notes

        must, care = [], []
        for g in groups:
            record = {
                'category': g['category'],
                'sev_label': sev_label_map.get(g['severity'], g['severity']),
                'title': g.get('title', 'Not described'),
                'detail': g.get('risk', ''),
                'suggestion': g.get('advice', ''),
                'hits': g.get('hits', []),
            }
            is_core_risk = g.get('core') and g['severity'] in ('CRITICAL', 'HIGH')
            if is_core_risk and len(must) < MAX_MUST_CONFIRM_ITEMS:
                must.append(record)
            else:
                care.append(record)

        return must, care

    def _parse_issue_message(self, msg: str) -> Tuple[str, str, str]:
        """Best-effort extraction of title / detail / suggestion from raw message.

        Rules:
        - If contains suggestion separator (CN colon variants), right side becomes suggestion;
        - If contains brackets [xxx], text before [] becomes title (or text inside []);
        - Text before colon becomes title, after colon becomes detail;
        - If none match, entire text becomes title.
        """
        if not msg:
            return 'Not described', '', ''

        suggestion = ''
        detail = ''
        title = msg

        # Extract suggestion
        for sep in ['建议：', '建议:']:
            if sep in msg:
                left, right = msg.split(sep, 1)
                suggestion = right.strip().rstrip('。').strip()
                msg = left.strip().rstrip('，,；;').strip()
                title = msg
                break

        # [xxx] prefix as title phrase
        if msg.startswith('['):
            end = msg.find(']')
            if end > 0:
                title_part = msg[1:end].strip()
                rest = msg[end + 1:].strip(' ：:')
                if title_part:
                    title = title_part
                if rest:
                    detail = rest
                return title[:80], detail[:400], suggestion[:300]

        # Colon-based splitting
        for colon in ['：', ':']:
            if colon in msg:
                left, right = msg.split(colon, 1)
                left, right = left.strip(), right.strip()
                if 0 < len(left) <= 40 and right:
                    title = left
                    detail = right
                    break

        return title[:80], detail[:400], suggestion[:300]
    
