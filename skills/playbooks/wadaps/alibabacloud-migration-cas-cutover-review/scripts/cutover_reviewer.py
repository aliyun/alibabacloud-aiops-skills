# IPv4
_REDACT_IPV4_RE = re.compile(r'\b(?:\d{1,3}\.){3}\d{1,3}\b')
# Email
_REDACT_EMAIL_RE = re.compile(r'\b[A-Za-z0-9._%+-]+@([A-Za-z0-9.-]+\.[A-Za-z]{2,})\b')
# Phone number (China mainland 11 digits)
_REDACT_PHONE_RE = re.compile(r'(?<!\d)1[3-9]\d{9}(?!\d)')
# Alibaba Cloud database/cache instance IDs (common prefixes: rm-/r-/dds-/gp-/dts-/pc-/redis-/mysql-)
_REDACT_INSTANCE_RE = re.compile(
    r'\b(rm|r|dds|gp|dts|pc|redis|mysql|kvstore|drds|polardb|mongodb)-[A-Za-z0-9]{6,}\b',
    re.IGNORECASE,
)
# Internal domains (*.internal / *-inc.com / *.alibaba-inc.com / gts.work etc.)
_REDACT_INTERNAL_DOMAIN_RE = re.compile(
    r'\b(?:[A-Za-z0-9-]+\.)+(?:[A-Za-z0-9-]*-inc\.com|internal|work|corp|local)\b',
    re.IGNORECASE,
)


def redact_text(text: str) -> str:
    """Redact sensitive fields in a text segment.

    Args:
        text: Original text (markdown / json string are both acceptable)

    Returns:
        Redacted text; non-string values are returned as-is.
    """
    if not isinstance(text, str) or not text:
        return text
    text = _REDACT_IPV4_RE.sub('***.***.***.***', text)
    text = _REDACT_EMAIL_RE.sub(r'***@\1', text)
    text = _REDACT_PHONE_RE.sub('***********', text)
    text = _REDACT_INSTANCE_RE.sub(lambda m: f"{m.group(1).lower()}-***", text)
    text = _REDACT_INTERNAL_DOMAIN_RE.sub('***.internal', text)
    return text


def redact_obj(obj: Any) -> Any:
    """Recursively redact: dict / list / str; other types are returned as-is."""
    if isinstance(obj, str):
        return redact_text(obj)
    if isinstance(obj, dict):
        return {k: redact_obj(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [redact_obj(i) for i in obj]
    if isinstance(obj, tuple):
        return tuple(redact_obj(i) for i in obj)
    return obj


