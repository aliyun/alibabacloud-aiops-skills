class TimeoutError(Exception):
    """Timeout exception"""
    pass


def run_with_timeout(func, args=(), kwargs=None, timeout=60, description="operation"):
    """Execute a function within a specified timeout; raises TimeoutError if exceeded.

    Args:
        func: The function to execute
        args: Positional arguments for the function
        kwargs: Keyword arguments for the function
        timeout: Timeout duration (seconds)
        description: Operation description (used in error messages)

    Returns:
        The function's return value

    Raises:
        TimeoutError: Execution timed out
    """
    if kwargs is None:
        kwargs = {}

    result = [None]
    exception = [None]

    def target():
        try:
            result[0] = func(*args, **kwargs)
        except Exception as e:
            exception[0] = e

    thread = threading.Thread(target=target, daemon=True)
    thread.start()
    thread.join(timeout)

    if thread.is_alive():
        raise TimeoutError(f"{description} timed out (exceeded {timeout} seconds), please check if the input file is abnormal")
    if exception[0] is not None:
        raise exception[0]
    return result[0]

